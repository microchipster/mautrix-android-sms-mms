# make-cdn-fixtures.sh — regenerate the deterministic fixtures used by the
# bridge file-service matrix (t20_cdn.sh):
#
#   tiny.png   deterministic 64x64 RGB PNG (python3 zlib, no metadata)
#   tiny.pdf   deterministic single-page PDF (fixed content, computed xref)
#
# Both are written by python3 from stdlib primitives only (struct/zlib), so
# bytes are reproducible across machines unless python's zlib encoder changes.
# The CDN matrix hashes the local files on disk, not pinned upstream hashes.
#
# The short video fixture (tiny.mp4) is generated by make-media-fixtures.sh
# alongside the other media fixtures; t20_cdn.sh only needs it to exist when a
# video round-trip is added.
#
# Usage:
#   scripts/validate/fixtures/make-cdn-fixtures.sh [output-dir]
#
# Requires python3.

set -euo pipefail

OUT_DIR="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)}"
mkdir -p "$OUT_DIR"

command -v python3 >/dev/null 2>&1 || { echo "python3 is required" >&2; exit 1; }

python3 - "$OUT_DIR" <<'PY'
import os
import struct
import sys
import zlib

out_dir = sys.argv[1]


def png_chunk(tag: bytes, data: bytes) -> bytes:
    return (
        struct.pack(">I", len(data))
        + tag
        + data
        + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
    )


def build_png() -> bytes:
    width = height = 64
    raw = bytearray()
    for y in range(height):
        raw.append(0)  # filter type 0 (None)
        for x in range(width):
            raw += bytes(((x * 4) % 256, (y * 4) % 256, ((x + y) * 2) % 256))
    ihdr = struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + png_chunk(b"IHDR", ihdr)
        + png_chunk(b"IDAT", zlib.compress(bytes(raw), 9))
        + png_chunk(b"IEND", b"")
    )


def build_pdf() -> bytes:
    content = b"BT /F1 10 Tf 12 70 Td (CDN validation fixture) Tj ET"
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 200 100]"
        b" /Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
        b"<< /Length " + str(len(content)).encode("ascii") + b" >>\nstream\n"
        + content
        + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for number, body in enumerate(objects, 1):
        offsets.append(len(out))
        out += str(number).encode("ascii") + b" 0 obj\n" + body + b"\nendobj\n"
    xref_offset = len(out)
    out += b"xref\n0 " + str(len(objects) + 1).encode("ascii") + b"\n"
    out += b"0000000000 65535 f \n"
    for offset in offsets:
        out += ("%010d 00000 n \n" % offset).encode("ascii")
    out += (
        b"trailer\n<< /Size "
        + str(len(objects) + 1).encode("ascii")
        + b" /Root 1 0 R >>\nstartxref\n"
        + str(xref_offset).encode("ascii")
        + b"\n%%EOF\n"
    )
    return bytes(out)


for name, payload in (("tiny.png", build_png()), ("tiny.pdf", build_pdf())):
    path = os.path.join(out_dir, name)
    with open(path, "wb") as handle:
        handle.write(payload)
PY

for f in tiny.png tiny.pdf; do
	size="$(stat --format=%s "$OUT_DIR/$f")"
	sum="$(sha256sum "$OUT_DIR/$f" | cut -d ' ' -f 1)"
	printf 'wrote %s (%s bytes, sha256 %s)\n' "$OUT_DIR/$f" "$size" "$sum"
	if [ "$size" -gt 100000 ]; then
		printf 'error: %s exceeds 100000 bytes\n' "$f" >&2
		exit 1
	fi
done
